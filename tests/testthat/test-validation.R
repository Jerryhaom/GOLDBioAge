test_that("invalid survival inputs fail with actionable errors", {
  expect_error(gold_bioage(test_data, "marker_risk"), "age")
  expect_error(gold_bioage(test_data, c("age", "absent")), "Missing columns")
  expect_error(gold_bioage(test_data, c("age", "age")), "unique")
  expect_error(gold_bioage(transform(test_data, status = 2), test_vars), "0 = censored")
  expect_error(gold_bioage(transform(test_data, time = -1), test_vars), "non-negative")
  expect_error(gold_bioage(transform(test_data, time = Inf), test_vars), "not Inf")
  expect_error(gold_bioage(transform(test_data, marker_risk = "x"), test_vars), "numeric")
  expect_error(gold_bioage(transform(test_data, status = 0), test_vars), "observed event")
  expect_error(gold_bioage(transform(test_data, age = 50), test_vars), "must vary")
  expect_error(gold_bioage(test_data, test_vars, feature_selection = NA), "TRUE or FALSE")
  expect_error(gold_bioage(test_data, test_vars, family = "gaussian"), "must be 'cox'")
  expect_error(gold_bioage(test_data, test_vars, seed = 1.5), "non-negative integer")
})

test_that("Cox variable order and the age-only case are handled", {
  a <- cox_bioage(test_data, test_vars)
  b <- cox_bioage(test_data, c("marker_risk", "age", "marker_protective", "noise"))
  expect_equal(a$coefficients, b$coefficients)
  expect_equal(a$CoxBioage$Coxbioage, b$CoxBioage$Coxbioage)
  expect_type(a$CoxBioage$Coxbioage, "double")
  only_age <- cox_bioage(test_data, "age")
  expect_equal(only_age$CoxBioage$Coxbioage, test_data$age)
})
